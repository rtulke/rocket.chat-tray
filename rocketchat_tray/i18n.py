SUPPORTED_LANGUAGES = ("de", "en", "fr", "it", "es")
DEFAULT_LANGUAGE = "en"


def _detect_language() -> str:
    code = QLocale.system().name()[:2].lower()
    return code if code in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


# Detected once at startup from the system locale (e.g. GNOME's own
# Language setting, via $LANG) -- no in-app language switcher, matching
# what was asked for ("follow the system language"), so this only needs to
# be a plain module-level constant, not something re-evaluated at runtime.
LANGUAGE = _detect_language()

